import type { Exercise, Stance } from '@/domain/types';

/**
 * Curated v1 library (~75 exercises). Every record carries the full safety tagging
 * from Section 4.2. A handful of intentionally EXCLUDED and CAUTION exercises are
 * included so the filter engine is exercised for real and the tests prove they never
 * surface in a plan or a swap.
 *
 * Media: each exercise points at a stance pictogram under /media/ by default. When
 * `scripts/fetch-exercisedb.mjs` has been run, a GIF entry is added by the media
 * manifest at runtime (see src/data/media.ts).
 * // DECISION NEEDED: confirm ExerciseDB licensing before shipping their GIFs.
 */

type ExInput = Omit<Exercise, 'media' | 'lessonIds' | 'exclusionTags' | 'cautionTags' | 'musclesSecondary' | 'unilateral' | 'impact'> &
  Partial<Pick<Exercise, 'media' | 'lessonIds' | 'exclusionTags' | 'cautionTags' | 'musclesSecondary' | 'unilateral' | 'impact'>>;

const stanceMedia = (stance: Stance) => ({ type: 'svg' as const, src: `/media/stance-${stance}.svg` });

function ex(e: ExInput): Exercise {
  return {
    impact: 'none',
    exclusionTags: [],
    cautionTags: [],
    lessonIds: [],
    musclesSecondary: [],
    unilateral: false,
    media: [stanceMedia(e.stance)],
    ...e,
  };
}

